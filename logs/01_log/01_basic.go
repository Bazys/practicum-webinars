// Пример 1: базовые функции пакета log — Print/Printf/Println, Fatal, Panic.
//
// Запуск:
//
//	go run ./01_log/01_basic.go
//
// Что демонстрирует:
//   - разница между Print*, Fatal*, Panic*
//   - стандартный формат вывода (дата + время)
//   - что происходит после вызова Fatal/Panic
package main

import (
	"errors"
	"fmt"
	"log"
)

func main() {
	// 1) Обычная запись в лог — программа продолжается.
	log.Println("сервер запущен")
	log.Printf("слушаю порт %d\n", 8080)

	// 2) Форматирование: Printf поддерживает глаголы fmt.
	user := "alice"
	log.Printf("пользователь %q вошёл в систему", user)

	// 3) Panic: пишет в лог и вызывает panic(msg).
	//    Deferred-функции ВЫПОЛНЯТСЯ, panic можно перехватить recover.
	defer func() {
		if r := recover(); r != nil {
			fmt.Println("\n[перехвачено recover]:", r)
		}
	}()

	// 4) Смоделируем ошибку, которую «не получилось» обработать.
	err := errors.New("что-то пошло не так")
	if err != nil {
		// Раскомментируйте, чтобы увидеть panic и recover:
		// log.Panic("паника:", err)

		// А пока просто залогируем как обычное сообщение.
		log.Printf("предупреждение: %v", err)
	}

	// 5) Fatal: пишет в лог и вызывает os.Exit(1).
	//    Deferred-функции НЕ выполнятся! Программа завершится немедленно.
	//
	// Раскомментируйте строку ниже, чтобы увидеть, как программа
	// завершается с кодом 1 (defer fmt.Println не успеет сработать).
	//
	// log.Fatal("фатальная ошибка, выходим")

	fmt.Println("\nпрограмма завершилась нормально")
}
